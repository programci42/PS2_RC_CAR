static const char *ui_translate(const char *en, int language)
{
    unsigned int i;
    if (!language || !en) return en;
    for (i = 0; i < sizeof(ui_translations)/sizeof(ui_translations[0]); i++)
        if (strcmp(en, ui_translations[i].en) == 0) return ui_translations[i].tr;
    return en;
}
